// Shared token STRUCTURE + generator. Values live in each app's own tokens.json.
//
// tokens.json shape (see README):
//   color.tokens[]  { name, value: string | { light, dark } }
//   shadow.tokens[] { name, value: string | { light, dark } }
//   type.families   { sans, display, serif, mono }
//   type.groups[]   { styles: [{ name, fontSize, lineHeight, fontWeight, letterSpacing? }] }
//   spacing|radius|blur .tokens[] { name, value }

/** Throws a readable error when a tokens object does not match the shared structure. */
export function validateTokens(t) {
  const need = (cond, msg) => {
    if (!cond) throw new Error(`tokens.json: ${msg}`)
  }
  need(Array.isArray(t?.color?.tokens), 'color.tokens[] missing')
  need(Array.isArray(t?.shadow?.tokens), 'shadow.tokens[] missing')
  need(t?.type?.families, 'type.families missing')
  need(Array.isArray(t?.type?.groups), 'type.groups[] missing')
  for (const k of ['spacing', 'radius', 'blur']) need(Array.isArray(t?.[k]?.tokens), `${k}.tokens[] missing`)
}

/**
 * Build the CSS custom-property sheet.
 * @param {object} t parsed tokens.json
 * @param {{ header?: string, darkSelector?: string }} [opts]
 *   header: text of the leading comment; darkSelector: where the dark theme applies
 *   (default ':root[data-reading]' inside prefers-color-scheme: dark).
 */
export function tokensToCss(t, opts = {}) {
  validateTokens(t)
  const header = opts.header ?? 'GENERATED by @space/tokens. Do not edit.'
  const darkSelector = opts.darkSelector ?? ':root[data-reading]'

  const themed = (theme) => {
    const out = []
    for (const c of t.color.tokens) out.push(`  --${c.name}: ${c.value[theme] ?? c.value};`)
    for (const s of t.shadow.tokens) {
      out.push(`  --${s.name}: ${typeof s.value === 'string' ? s.value : s.value[theme]};`)
    }
    return out
  }
  const fixed = () => {
    const out = []
    out.push(`  --font-sans: ${t.type.families.sans};`)
    out.push(`  --font-display: ${t.type.families.display};`)
    out.push(`  --font-serif: ${t.type.families.serif};`)
    out.push(`  --font-mono: ${t.type.families.mono};`)
    for (const g of t.type.groups) {
      for (const s of g.styles) {
        out.push(`  --type-${s.name}-size: ${s.fontSize};`)
        out.push(`  --type-${s.name}-line: ${s.lineHeight};`)
        out.push(`  --type-${s.name}-weight: ${s.fontWeight};`)
        if (s.letterSpacing) out.push(`  --type-${s.name}-tracking: ${s.letterSpacing};`)
      }
    }
    for (const k of ['spacing', 'radius', 'blur']) {
      for (const x of t[k].tokens) out.push(`  --${x.name}: ${x.value};`)
    }
    return out
  }

  return `/* ${header} */
:root {
  color-scheme: light;
${fixed().join('\n')}
${themed('light').join('\n')}
}

/* Basalt (dark) only applies in reading contexts, which opt in with <html data-reading>.
   The landing page and index pages are always Birch (light). */
@media (prefers-color-scheme: dark) {
  ${darkSelector} {
    color-scheme: dark;
${themed('dark').join('\n').replace(/^ {2}/gm, '    ')}
  }
}
`
}
