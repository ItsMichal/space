// ::map and its data. The place list is hand-auditable (content/maps.ts names its two Wayback snapshots); these checks keep it
// consistent with itself and with the baked Natural Earth raster, and the directives (::map, ::stat) through the renderer and
// the backstop.
import fs from 'node:fs'
import path from 'node:path'
import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, it } from 'vitest'
import { markdownToHast } from '@/lib/content/render'
import { hastToReact } from '@/lib/content/to-react'
import { bodyProblems, directiveAttrs } from '@/lib/content/rules.mjs'
import { mapById, maps } from '@/content/maps'
import * as world from '../world.gen'
import { decodeWorld, dotRadius, pitchFor } from '../geometry'

const starlink = maps['starlink-markets']

describe('map data', () => {
  it('lists each place once, with a valid alpha-2 code and the name Intl knows it by', () => {
    const dn = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'none' })
    for (const m of Object.values(maps)) {
      const codes = m.places.map((p) => p[0])
      expect(new Set(codes).size).toBe(codes.length)
      for (const [code, iso, name] of m.places) {
        expect(code).toMatch(/^[A-Z]{2}$/)
        expect(iso).toMatch(/^(\d{3}|XK)$/)
        expect(dn.of(code), code).toBeTruthy()
        expect(name.trim()).toBe(name)
      }
    }
  })

  it('starlink-markets has the 84 places of the snapshot diff and cites both snapshots', () => {
    expect(starlink.places).toHaveLength(84)
    expect(starlink.sources.map((s) => s.url)).toEqual([
      'https://web.archive.org/web/20240415120500/https://api.starlink.com/public-files/availability.json',
      'https://web.archive.org/web/20261015051932/https://starlink.com/public-files/availability.json',
    ])
    // already live on 15 April 2024, so never on this map
    for (const code of ['US', 'CA', 'GB', 'MX', 'BR', 'NG', 'JP', 'AU', 'PL', 'MW']) expect(starlink.places.map((p) => p[0])).not.toContain(code)
  })

  it('draws every place but Bouvet Island, which Natural Earth has no shape for', () => {
    const w = decodeWorld(world)
    const missing = starlink.places.filter(([, iso]) => w.index(iso) < 0 && !w.points[iso]).map((p) => p[0])
    expect(missing).toEqual(['BV'])
  })

  it('pairs each numeric code with the country Natural Earth names for it', () => {
    // spot checks on codes that are easy to swap: the two Congos, the two Koreas, Niger and Nigeria, Guinea and its neighbours
    expect(world.WORLD_NAMES['180']).toMatch(/Dem\. Rep\. Congo/)
    expect(world.WORLD_NAMES['178']).toBe('Congo')
    expect(world.WORLD_NAMES['410']).toBe('South Korea')
    expect(world.WORLD_NAMES['562']).toBe('Niger')
    expect(world.WORLD_NAMES['624']).toBe('Guinea-Bissau')
    expect(world.WORLD_NAMES.XK).toBe('Kosovo')
    expect(starlink.places.map((p) => p[0])).not.toContain('CG')
  })
})

describe('world raster', () => {
  const w = decodeWorld(world)
  it('decodes to whole rows, sea round the edges and off the map in the corners', () => {
    for (const runs of world.WORLD_ROWS) expect(runs.filter((_, i) => i % 2).reduce((a, b) => a + b, 0)).toBe(world.WORLD_W)
    expect(w.at(0, 0)).toBe(0)
    expect(w.at(-1, 10)).toBe(0)
    expect(w.at(world.WORLD_W / 2, world.WORLD_H / 2 + 20)).toBe(1) // the Gulf of Guinea
  })

  it('finds a country at its own marker point, so hover and the list agree', () => {
    for (const iso of ['360', '840', '076', '643', '710']) expect(w.ids[w.at(...w.points[iso])], iso).toBe(iso)
    expect(w.index('360')).toBeGreaterThan(1)
    expect(w.index('sea')).toBe(-1)
  })

  it('swells the hovered country and keeps the sea a speck', () => {
    const p = pitchFor(672)
    expect(p).toBe(6) // the globe's grid on a desktop post
    expect(pitchFor(326)).toBe(3.5) // tighter on a phone
    expect(dotRadius(p, 1, false, false)).toBeLessThan(dotRadius(p, 5, false, false))
    expect(dotRadius(p, 5, false, false)).toBeLessThan(dotRadius(p, 5, true, false))
    expect(dotRadius(p, 5, true, false)).toBeLessThan(dotRadius(p, 5, true, true))
    expect(dotRadius(p, 5, true, true)).toBeLessThan(p / 2)
  })

  it('is what the bake script makes (run node scripts/build-world-map.mjs after changing it)', () => {
    const src = fs.readFileSync(path.join(__dirname, '../world.gen.ts'), 'utf8')
    expect(src).toMatch(/^\/\/ Generated by scripts\/build-world-map\.mjs/)
    expect(world.WORLD_ROWS).toHaveLength(world.WORLD_H)
    expect(world.WORLD_IDS.slice(0, 2)).toEqual(['', 'sea'])
  })
})

describe('::map directive', () => {
  it('keeps a slug id and drops anything else', () => {
    expect(directiveAttrs('map', { id: 'starlink-markets', onload: 'x' })).toEqual({ id: 'starlink-markets' })
    for (const id of [undefined, '', 'Starlink', '../x', 'a b', 'a--b']) expect(directiveAttrs('map', { id })).toBeNull()
    expect(bodyProblems('::map{id=starlink-markets}')).toEqual([])
    expect(bodyProblems('::map')[0]).toMatch(/::map has a missing or disallowed id/)
  })

  it('renders the frame, its list and sources (the world loads in the browser), and nothing for an unknown id', async () => {
    const html = renderToStaticMarkup(hastToReact(await markdownToHast('Intro.\n\n::map{id=starlink-markets}\n')))
    expect(html).toContain('class="wmap"')
    expect(html).toMatch(/class="wmap__frame" role="img" aria-label="World map with 84 places lit: [^"]*Indonesia/)
    expect(html).toContain('<canvas class="wmap__canvas" aria-hidden="true"></canvas>')
    expect(html).toContain('Went live: 84 places')
    expect(html).toContain('<li>Indonesia</li>')
    expect(html).toContain('href="https://web.archive.org/web/20240415120500/')
    for (const id of ['nope', 'constructor', 'to-string']) {
      expect(mapById(id)).toBeUndefined()
      expect(renderToStaticMarkup(hastToReact(await markdownToHast(`::map{id=${id}}`)))).toBe('')
    }
  })

  it('takes no attribute but the id', async () => {
    const hast = await markdownToHast('::map{id=starlink-markets geo="{}" style="x"}')
    expect(JSON.stringify(hast)).not.toMatch(/"geo"|"style"/)
  })
})

describe('::stat directive', () => {
  it('keeps a short value and a label, trimmed, and drops anything else', () => {
    expect(directiveAttrs('stat', { value: ' 84 ', label: ' countries ', onclick: 'x' })).toEqual({ value: '84', label: 'countries' })
    for (const attrs of [{ label: 'x' }, { value: '84' }, { value: ' ', label: 'x' }, { value: '84', label: ' ' }, { value: '1234567890123', label: 'x' }]) expect(directiveAttrs('stat', attrs)).toBeNull()
    expect(bodyProblems('::stat{value="84" label="countries"}')).toEqual([])
    expect(bodyProblems('::stat{value="84"}')[0]).toMatch(/::stat has a missing or disallowed value/)
  })

  it('renders the figure and its label as text', async () => {
    const html = renderToStaticMarkup(hastToReact(await markdownToHast('::stat{value="84" label="countries <b>and</b> territories"}')))
    expect(html).toBe('<p class="stat"><span class="stat__value">84</span><span class="stat__label t-text">countries &lt;b&gt;and&lt;/b&gt; territories</span></p>')
  })
})
