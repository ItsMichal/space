// ::map and its data. The place list is hand-auditable (content/maps.ts names its two Wayback snapshots); these checks keep it
// consistent with itself and with the baked Natural Earth shapes, and the directive through the renderer, the backstop and
// the build-time inline.
import fs from 'node:fs'
import path from 'node:path'
import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, it } from 'vitest'
import { markdownToHast } from '@/lib/content/render'
import { hastToReact } from '@/lib/content/to-react'
import { bodyProblems, directiveAttrs } from '@/lib/content/rules.mjs'
import { mapById, maps } from '@/content/maps'
import * as world from '../world.gen'
import { mapGeometry, parseGeo } from '../geometry'
import { inlineMaps } from '../inline.server'

const starlink = maps['starlink-markets']

describe('map data', () => {
  it('lists each place once, with a valid alpha-2 code and the name Intl knows it by', () => {
    const dn = new Intl.DisplayNames(['en'], { type: 'region', fallback: 'none' })
    for (const m of Object.values(maps)) {
      const codes = m.places.map((p) => p[0])
      expect(new Set(codes).size).toBe(codes.length)
      for (const [code, iso, name] of m.places) {
        expect(code).toMatch(/^[A-Z]{2}$/)
        expect(iso).toMatch(/^(\d{3}|XK)$/)
        expect(dn.of(code), code).toBeTruthy()
        expect(name.trim()).toBe(name)
      }
    }
  })

  it('starlink-markets has the 84 places of the snapshot diff and cites both snapshots', () => {
    expect(starlink.places).toHaveLength(84)
    expect(starlink.sources.map((s) => s.url)).toEqual([
      'https://web.archive.org/web/20240415120500/https://api.starlink.com/public-files/availability.json',
      'https://web.archive.org/web/20261015051932/https://starlink.com/public-files/availability.json',
    ])
    // already live on 15 April 2024, so never on this map
    for (const code of ['US', 'CA', 'GB', 'MX', 'BR', 'NG', 'JP', 'AU', 'PL', 'MW']) expect(starlink.places.map((p) => p[0])).not.toContain(code)
  })

  it('draws every place but Bouvet Island, which Natural Earth has no shape for', () => {
    const g = mapGeometry(starlink, world)
    const drawn = new Set([...g.lit.map((l) => l[0]), ...g.dots.map((d) => d[0])])
    expect(starlink.places.filter((p) => !drawn.has(p[0])).map((p) => p[0])).toEqual(['BV'])
  })

  it('pairs each numeric code with the shape Natural Earth names for that country', () => {
    // spot checks on codes that are easy to swap: the two Congos, the two Koreas, Niger and Nigeria, Guinea and its neighbours
    const g = mapGeometry(starlink, world)
    const lit = new Map(g.lit)
    expect(lit.get('CD')).toBe(world.WORLD_SHAPES['180'])
    expect(lit.get('KR')).toBe(world.WORLD_SHAPES['410'])
    expect(lit.get('NE')).toBe(world.WORLD_SHAPES['562'])
    expect(lit.get('GW')).toBe(world.WORLD_SHAPES['624'])
    expect(lit.get('XK')).toBe(world.WORLD_SHAPES.XK)
    expect(lit.has('CG')).toBe(false)
  })
})

describe('world geometry', () => {
  it('keeps every shape inside the frame bar the antimeridian copies, and lit countries out of the base', () => {
    const g = mapGeometry(starlink, world)
    expect(g.base).not.toContain(world.WORLD_SHAPES['360']) // Indonesia is lit
    expect(g.base).toContain(world.WORLD_SHAPES['840']) // the US is not
    for (const [, x, y] of g.dots) {
      expect(x).toBeGreaterThanOrEqual(0)
      expect(x).toBeLessThanOrEqual(world.WORLD_W)
      expect(y).toBeGreaterThanOrEqual(0)
      expect(y).toBeLessThanOrEqual(world.WORLD_H)
    }
  })

  it('is what the bake script makes (run node scripts/build-world-map.mjs after changing it)', () => {
    const src = fs.readFileSync(path.join(__dirname, '../world.gen.ts'), 'utf8')
    expect(src).toMatch(/^\/\/ Generated by scripts\/build-world-map\.mjs/)
    expect(Object.keys(world.WORLD_SHAPES)).toHaveLength(175)
  })

  it('parses only a well formed geo prop', () => {
    const g = mapGeometry(starlink, world)
    expect(parseGeo(JSON.stringify(g))).toEqual(g)
    for (const bad of [undefined, '', '{', '{"base":1}', JSON.stringify({ ...g, w: 0 }), 42]) expect(parseGeo(bad)).toBeNull()
  })
})

describe('::map directive', () => {
  it('keeps a slug id and drops anything else', () => {
    expect(directiveAttrs('map', { id: 'starlink-markets', onload: 'x' })).toEqual({ id: 'starlink-markets' })
    for (const id of [undefined, '', 'Starlink', '../x', 'a b', 'a--b']) expect(directiveAttrs('map', { id })).toBeNull()
    expect(bodyProblems('::map{id=starlink-markets}')).toEqual([])
    expect(bodyProblems('::map')[0]).toMatch(/::map has a missing or disallowed id/)
  })

  it('renders the map, inlined at build time, with its list and sources', async () => {
    const hast = inlineMaps(await markdownToHast('Intro.\n\n::map{id=starlink-markets}\n'))
    const html = renderToStaticMarkup(hastToReact(hast))
    expect(html).toContain('class="wmap"')
    expect(html).toContain('<svg class="wmap__svg" viewBox="0 0 1000 487" role="img"')
    expect(html).toContain('Went live: 84 places')
    expect(html.match(/class="wmap__lit"/g)?.length).toBeGreaterThan(40)
    expect(html).toContain('<li>Indonesia</li>')
    expect(html).toContain('href="https://web.archive.org/web/20240415120500/')
  })

  it('renders the frame without a drawing when nothing was inlined (the editor preview loads it), and nothing for an unknown id', async () => {
    const html = renderToStaticMarkup(hastToReact(await markdownToHast('::map{id=starlink-markets}')))
    expect(html).toContain('class="wmap__frame"></div>')
    expect(html).toContain('Went live: 84 places')
    for (const id of ['nope', 'constructor', 'to-string']) {
      expect(mapById(id)).toBeUndefined()
      expect(renderToStaticMarkup(hastToReact(inlineMaps(await markdownToHast(`::map{id=${id}}`))))).toBe('')
    }
  })

  it('cannot be handed a drawing from the markdown', async () => {
    const hast = await markdownToHast('::map{id=starlink-markets geo="{}"}')
    expect(JSON.stringify(hast)).not.toContain('"geo"')
  })
})
