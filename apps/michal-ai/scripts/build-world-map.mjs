// Bakes Natural Earth country shapes (public domain, via the world-atlas TopoJSON redistribution) into lib/maps/world.gen.ts:
// SVG path data per country in an Equal Earth projection, for the ::map directive (components/mdx/WorldMap.tsx).
//   shapes  countries-110m outlines, keyed by ISO 3166-1 numeric code (Kosovo, which has none, as XK)
//   dots    a marker point for every country that 110m leaves out or draws smaller than a few pixels (islands, city states),
//           at the centre of its largest 10m polygon
// Run manually (`node scripts/build-world-map.mjs`); the output is committed so builds need no dev dependency.
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const load = (res) => {
  const topo = JSON.parse(fs.readFileSync(require.resolve(`world-atlas/countries-${res}.json`), 'utf8'))
  return feature(topo, topo.objects.countries).features
}
// Natural Earth gives a few places no ISO number; the one a map can name is Kosovo (XK, a user-assigned code)
const idOf = (f) => f.id ?? (f.properties.name === 'Kosovo' ? 'XK' : null)

// Equal Earth (Šavrič, Patterson, Jenny 2018), in units where the full width is W
const W = 1000
const [A1, A2, A3, A4] = [1.340264, -0.081106, 0.000893, 0.003796]
const M = Math.sqrt(3) / 2
const raw = (lon, lat) => {
  const t = Math.asin(M * Math.sin((lat * Math.PI) / 180))
  const t2 = t * t
  const t6 = t2 * t2 * t2
  return [((lon * Math.PI) / 180) * Math.cos(t) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2))), t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2))]
}
const [xMax] = raw(180, 0)
const [, yMax] = raw(0, 90)
const k = W / (2 * xMax)
const H = Math.round(2 * yMax * k)
// x is linear in longitude, so a point past 180 lands past the edge (used by unwrap below)
const project = ([lon, lat]) => {
  const [x, y] = raw(lon, lat)
  return [(x + xMax) * k, (yMax - y) * k]
}

const polygons = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [])
const r1 = (n) => Math.round(n * 10) / 10

/** A ring that crosses the antimeridian (Fiji, Chukotka) is drawn twice, once unwrapped east and once west; the SVG clips it. */
function unwrap(ring) {
  // a step from +180 to -180 is Antarctica's edge along the bottom of the map, not a crossing
  const crosses = ring.some(([lon], i) => i && Math.abs(lon - ring[i - 1][0]) > 180 && !(Math.abs(lon) === 180 && Math.abs(ring[i - 1][0]) === 180))
  if (!crosses) return [ring]
  const east = ring.map(([lon, lat]) => [lon < 0 ? lon + 360 : lon, lat])
  return [east, east.map(([lon, lat]) => [lon - 360, lat])]
}

/** One closed subpath per ring, relative moves at 0.1 unit; rings that collapse to under three points are dropped. */
function pathOf(f) {
  let d = ''
  for (const poly of polygons(f.geometry)) {
    for (const ring of poly.flatMap(unwrap)) {
      const pts = ring.map(project).map(([x, y]) => [Math.round(x * 10), Math.round(y * 10)])
      const kept = pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1])
      if (kept.length < 4) continue
      let [px, py] = kept[0]
      d += `M${r1(px / 10)} ${r1(py / 10)}`
      let seg = ''
      for (const [x, y] of kept.slice(1, -1)) {
        seg += `${seg ? ' ' : 'l'}${r1((x - px) / 10)} ${r1((y - py) / 10)}`
        ;[px, py] = [x, y]
      }
      d += `${seg}z`
    }
  }
  return d.replace(/ -/g, '-').replace(/(^|[ lM-])0\./g, '$1.')
}

/** Planar area and centroid of a projected ring (shoelace). */
function ringStats(ring) {
  const pts = ring.map(project)
  let a = 0
  let cx = 0
  let cy = 0
  for (let i = 0; i < pts.length - 1; i++) {
    const [x0, y0] = pts[i]
    const [x1, y1] = pts[i + 1]
    const c = x0 * y1 - x1 * y0
    a += c
    cx += (x0 + x1) * c
    cy += (y0 + y1) * c
  }
  return a ? { area: Math.abs(a / 2), at: [cx / (3 * a), cy / (3 * a)] } : { area: 0, at: pts[0] }
}
const area = (f) => polygons(f.geometry).reduce((s, p) => s + ringStats(p[0]).area, 0)

const shapes = {}
for (const f of load('110m')) {
  const id = idOf(f)
  if (id) shapes[id] = pathOf(f)
}
// under ~12 square units (a few pixels across at phone width) a shape needs a marker to be seen
const TINY = 12
const small = new Set(load('110m').filter((f) => idOf(f) && area(f) < TINY).map(idOf))
const dots = {}
for (const f of load('10m')) {
  const id = idOf(f)
  if (!id || (shapes[id] && !small.has(id))) continue
  const biggest = polygons(f.geometry)
    .map((p) => ringStats(p[0]))
    .sort((a, b) => b.area - a.area)[0]
  if (biggest) dots[id] = biggest.at.map(r1)
}

const out = `// Generated by scripts/build-world-map.mjs from Natural Earth (public domain) via world-atlas. Do not edit by hand.
// Equal Earth projection; x runs 0..${W}, y 0..${H}. Keys are ISO 3166-1 numeric codes (XK for Kosovo).
export const WORLD_W = ${W}
export const WORLD_H = ${H}
export const WORLD_SHAPES: Record<string, string> = ${JSON.stringify(shapes)}
export const WORLD_DOTS: Record<string, [number, number]> = ${JSON.stringify(dots)}
`
fs.writeFileSync(path.join(root, 'lib/maps/world.gen.ts'), out)
console.log(`lib/maps/world.gen.ts: ${Object.keys(shapes).length} shapes, ${Object.keys(dots).length} dots, ${(out.length / 1024).toFixed(1)} KB, ${W}x${H}`)
