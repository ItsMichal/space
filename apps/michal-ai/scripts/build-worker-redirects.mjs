// Writes worker/redirects.generated.ts from content/redirects.json via lib/redirects.mjs (the single source of truth for old URLs).
// Run by `npm run build` (and by the drift test in worker/redirects.test.ts, which fails if the committed file is stale).
// Usage: node scripts/build-worker-redirects.mjs [--check]
import fs from 'node:fs'
import path from 'node:path'
import { buildRedirects } from '../lib/redirects.mjs'

const root = path.resolve(import.meta.dirname, '..')
process.chdir(root)
const entries = Object.fromEntries(buildRedirects().map((r) => [r.source, r.destination]).sort(([a], [b]) => a.localeCompare(b)))
const out = `// GENERATED by scripts/build-worker-redirects.mjs from content/redirects.json. Do not edit; run \`npm run build:redirects\`.
// Old path to current path. The Worker answers each with a permanent (308) redirect, keeping the query string.
export const REDIRECTS: Record<string, string> = ${JSON.stringify(entries, null, 2)}
`
const file = path.join(root, 'worker', 'redirects.generated.ts')
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== out) {
    console.error('worker/redirects.generated.ts is stale: run npm run build:redirects -w @space/michal-ai')
    process.exit(1)
  }
} else fs.writeFileSync(file, out)
console.log(`worker redirects: ${Object.keys(entries).length}`)
