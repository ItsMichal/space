// Writes lib/presence/slugs.generated.ts: the stable post ids (and slugs) the live API accepts, published posts only.
// A Durable Object is created per post id, so the Worker must reject ids it did not ship with. The id is the frontmatter
// `id` (falls back to the slug) and never changes when a slug is renamed. Counts are keyed by id, never by URL.
// Run by `prebuild`; a unit test fails if the committed file drifts from content/posts.
import fs from 'node:fs'
import path from 'node:path'
import matter from 'gray-matter'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const dir = path.join(root, 'content', 'posts')
const slugs = []
const ids = []
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.md'))) {
  const { data } = matter(fs.readFileSync(path.join(dir, f), 'utf8'))
  if (data.draft) continue
  const slug = String(data.slug ?? f.replace(/\.md$/, ''))
  slugs.push(slug)
  ids.push(String(data.id ?? slug))
}
if (new Set(ids).size !== ids.length) throw new Error('Duplicate post ids in content/posts')
slugs.sort()
ids.sort()
const out =
  `// Generated by scripts/build-live-slugs.mjs. Do not edit.\n` +
  `export const LIVE_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)}\n` +
  `export const LIVE_IDS: readonly string[] = ${JSON.stringify(ids, null, 2)}\n`
const file = path.join(root, 'lib', 'presence', 'slugs.generated.ts')
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out)
