// Writes lib/presence/slugs.generated.ts: the slugs the reactions API accepts (published posts only).
// A Durable Object is created per slug, so the Worker must reject slugs it did not ship with.
// Run by `prebuild`; a unit test fails if the committed file drifts from content/posts.
import fs from 'node:fs'
import path from 'node:path'
import matter from 'gray-matter'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const dir = path.join(root, 'content', 'posts')
const slugs = []
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.md'))) {
  const { data } = matter(fs.readFileSync(path.join(dir, f), 'utf8'))
  if (data.draft) continue
  slugs.push(String(data.slug ?? f.replace(/\.md$/, '')))
}
slugs.sort()
const out = `// Generated by scripts/build-live-slugs.mjs. Do not edit.\nexport const LIVE_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)}\n`
const file = path.join(root, 'lib', 'presence', 'slugs.generated.ts')
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out)
