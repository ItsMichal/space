// Generates app/styles/tokens.css from docs/design-system/tokens.json (the generator lives in @space/tokens)
import fs from 'node:fs'
import path from 'node:path'
import { tokensToCss } from '@space/tokens'

const root = path.resolve(import.meta.dirname, '..')
const t = JSON.parse(fs.readFileSync(path.join(root, 'docs/design-system/tokens.json'), 'utf8'))
const css = tokensToCss(t, {
  header: 'GENERATED by scripts/tokens-to-css.mjs from docs/design-system/tokens.json. Do not edit.',
})
fs.mkdirSync(path.join(root, 'app/styles'), { recursive: true })
fs.writeFileSync(path.join(root, 'app/styles/tokens.css'), css)
console.log('wrote app/styles/tokens.css')
