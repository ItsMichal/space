// Generates app/styles/tokens.css from docs/design-system/tokens.json
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const t = JSON.parse(fs.readFileSync(path.join(root, 'docs/design-system/tokens.json'), 'utf8'))

const themed = (theme) => {
  const out = []
  for (const c of t.color.tokens) out.push(`  --${c.name}: ${c.value[theme] ?? c.value};`)
  for (const s of t.shadow.tokens) {
    out.push(`  --${s.name}: ${typeof s.value === 'string' ? s.value : s.value[theme]};`)
  }
  return out
}
const fixed = () => {
  const out = []
  out.push(`  --font-sans: ${t.type.families.sans};`)
  out.push(`  --font-serif: ${t.type.families.serif};`)
  out.push(`  --font-mono: ${t.type.families.mono};`)
  for (const g of t.type.groups) {
    for (const s of g.styles) {
      out.push(`  --type-${s.name}-size: ${s.fontSize};`)
      out.push(`  --type-${s.name}-line: ${s.lineHeight};`)
      out.push(`  --type-${s.name}-weight: ${s.fontWeight};`)
      if (s.letterSpacing) out.push(`  --type-${s.name}-tracking: ${s.letterSpacing};`)
    }
  }
  for (const k of ['spacing', 'radius', 'blur']) {
    for (const x of t[k].tokens) out.push(`  --${x.name}: ${x.value};`)
  }
  return out
}

const css = `/* GENERATED by scripts/tokens-to-css.mjs from docs/design-system/tokens.json. Do not edit. */
:root {
  color-scheme: light dark;
${fixed().join('\n')}
${themed('light').join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root {
${themed('dark').join('\n').replace(/^ {2}/gm, '    ')}
  }
}
`
fs.mkdirSync(path.join(root, 'app/styles'), { recursive: true })
fs.writeFileSync(path.join(root, 'app/styles/tokens.css'), css)
console.log('wrote app/styles/tokens.css')
